-- This migration creates empty tables and does not alter employee or salary history.
CREATE TABLE hr_payslips (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 payslip_no VARCHAR(40) NULL UNIQUE,
 outlet_id BIGINT UNSIGNED NOT NULL,
 employee_id BIGINT UNSIGNED NOT NULL,
 salary_history_id BIGINT UNSIGNED NOT NULL,
 staff_code_snapshot VARCHAR(50) NOT NULL,
 full_name_snapshot VARCHAR(150) NOT NULL,
 department_snapshot VARCHAR(150) NULL,
 position_snapshot VARCHAR(150) NULL,
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 pay_date DATE NOT NULL,
 salary_type VARCHAR(20) NOT NULL,
 currency_code CHAR(3) NOT NULL DEFAULT 'MYR',
 basic_pay DECIMAL(14,2) NOT NULL,
 fixed_allowance DECIMAL(14,2) NOT NULL DEFAULT 0,
 earnings_json LONGTEXT NOT NULL,
 deductions_json LONGTEXT NOT NULL,
 gross_pay DECIMAL(14,2) NOT NULL,
 total_deductions DECIMAL(14,2) NOT NULL,
 net_pay DECIMAL(14,2) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 notes VARCHAR(1000) NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 issued_by BIGINT UNSIGNED NULL,
 issued_at DATETIME NULL,
 voided_by BIGINT UNSIGNED NULL,
 voided_at DATETIME NULL,
 void_reason VARCHAR(500) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY ix_hr_payslip_employee_period(outlet_id,employee_id,period_start,period_end,status),
 KEY ix_hr_payslip_outlet_period(outlet_id,period_start,status),
 CONSTRAINT fk_hr_payslip_outlet FOREIGN KEY(outlet_id) REFERENCES outlets(id) ON DELETE RESTRICT,
 CONSTRAINT fk_hr_payslip_employee FOREIGN KEY(employee_id) REFERENCES hr_employees(id) ON DELETE RESTRICT,
 CONSTRAINT fk_hr_payslip_salary FOREIGN KEY(salary_history_id) REFERENCES hr_salary_history(id) ON DELETE RESTRICT,
 CONSTRAINT fk_hr_payslip_creator FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_hr_payslip_issuer FOREIGN KEY(issued_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_hr_payslip_voider FOREIGN KEY(voided_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
